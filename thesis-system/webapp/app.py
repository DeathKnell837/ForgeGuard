def masked_phone(phone):
    """Mask middle digits of phone number e.g. 0976 *** 7835"""
    p = str(phone).strip()
    parts = p.split()
    if len(parts) == 3:
        return f"{parts[0]} *** {parts[2]}"
    if len(p) >= 11:
        return f"{p[:4]} *** {p[-4:]}"
    return p

